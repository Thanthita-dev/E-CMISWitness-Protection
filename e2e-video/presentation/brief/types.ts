/**
 * ฉบับกระชับของวิดีโอนำเสนอ — แต่ละไฟล์ในโฟลเดอร์นี้ดูแลบทของกลุ่มฉากของตัวเอง แล้ว index.ts รวมให้ presenter/spec ใช้
 *
 * ในโหมดกระชับ (ค่าเริ่มต้น ปิดด้วย PRESENT_FULL=1):
 * - ป้ายที่อยู่ใน keep[ฉาก] ขึ้นจอและพากย์ด้วย speech[ป้าย] (ไม่มีก็ใช้ NOTE_SPEECH / ข้อความป้าย)
 * - ป้ายอื่น: d.highlight() ที่ชี้ให้ดูเฉย ๆ ถูกข้าม · การกด/กรอก/เลือกยังทำ (เห็นเคอร์เซอร์) แต่ไม่ขึ้นป้ายและไม่พากย์
 */
export interface BriefPack {
  /** บทพากย์เปิดฉากฉบับกระชับ แทน NARRATION[key] (ฉากที่ไม่ระบุใช้บทเดิม) */
  narration: Record<string, string>
  /** ป้ายที่ยังขึ้นจอและพากย์ ต่อคีย์ฉาก — ข้อความป้ายหลังตัดรหัส WIT (ตรงกับ notes ใน output-presentation/raw/presentation.json) */
  keep: Record<string, string[]>
  /** คำพากย์สั้นของป้ายที่เก็บไว้ คีย์คือข้อความป้าย */
  speech: Record<string, string>
}
