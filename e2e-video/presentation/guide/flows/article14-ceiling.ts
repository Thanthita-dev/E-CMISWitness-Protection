import type { GuideFlow } from '../types'
import { article14ProposalSteps } from './article14'

/**
 * ทางแยก: ทบทวนผลคุ้มครองครบเพดาน 180 วันแต่ยังมีภัย → ส่งต่อกรมคุ้มครองสิทธิฯ (ข้อ 14)
 * ใช้จุดพัก "Case 10" (เรื่อง WP-2569-000501 สะสม 180/180 วัน) เพราะเดินข้อมูล Demo ให้ถึงเพดานเองไม่ได้
 * ตั้งแต่ขั้นที่เข้าหน้า /article14 เดินต่อด้วยขั้นตอนชุดเดียวกับทางแยกของเลขาธิการฯ (article14ProposalSteps)
 */
const CASE_NO = 'WP-2569-000501'
const REVIEW = `/protection-review/${CASE_NO}`

export default {
  id: 'article14-ceiling',
  branchSection: 'ทบทวนผลคุ้มครองและเสนอยุติ',
  title: 'ทางแยก: ครบเพดาน 180 วันแต่ยังมีภัย → ส่งต่อกรมคุ้มครองสิทธิและเสรีภาพ',
  summary:
    'เมื่อทบทวนผลคุ้มครองแล้วพบว่าสะสมครบเพดาน 180 วันแต่ภัยยังไม่คลี่คลาย ขยายเวลาด้วย คบ.14 ไม่ได้ เจ้าหน้าที่เสนอแนวทางส่งต่อกรมคุ้มครองสิทธิและเสรีภาพ (ข้อ 14) ผ่านความเห็นชอบของผู้บังคับบัญชา แล้วเดินต่อเส้นทางส่งต่อ: ผบช.ชั้นต้น เลขาธิการฯ มติคณะกรรมการ ป.ป.ท. หนังสือถึงกรม หนังสือตอบรับ และส่งมอบ',
  caseNo: CASE_NO,
  prefix: async (d) => {
    await d.loadCheckpoint('Case 10', 'officer', REVIEW)
    d.currentRole = 'officer'
  },
  run: async (d) => {
    const p = d.page

    // ───────── ทบทวนที่ครบเพดาน ─────────
    d.section('ทบทวนผลคุ้มครองที่ครบเพดาน 180 วัน', 'เจ้าหน้าที่เปิดหน้าทบทวน เห็นยอดสะสมครบเพดานรวม 180 วัน จึงขยายระยะเวลาไม่ได้ ต้องเลือกแนวทางตามข้อ 14')
    await d.highlight(p.getByTestId('review-outcome-extend'), 'ขยายระยะเวลาเลือกไม่ได้ เพราะสะสมครบเพดาน 180/180 วันแล้ว')
    await d.click(p.getByTestId('review-outcome-article14'), { note: 'เลือกแนวทาง "ครบเพดานแต่ยังมีภัย — ส่งต่อกรมคุ้มครองสิทธิฯ"' })
    await d.fill(p.getByRole('textbox', { name: /ผลประเมินความเสี่ยงและความจำเป็น/ }), 'ภัยคุกคามยังไม่คลี่คลาย แต่คุ้มครองครบเพดานรวม 180 วันแล้ว ป.ป.ท. คุ้มครองต่อไม่ได้', { note: 'ประเมินความเสี่ยงและความจำเป็น' })
    await d.fill(p.getByPlaceholder('อ้างอิง คบ.13 คำสั่งเดิม และกรณีครบเพดานแต่ยังมีภัย'), 'อ้างอิง คบ.13 งวดล่าสุดและคำสั่งคุ้มครองเดิม ครบเพดาน 180 วันแต่ยังมีภัย เห็นควรส่งต่อกรมคุ้มครองสิทธิฯ', { note: 'เหตุผลและหลักฐานอ้างอิง' })
    await d.click(p.getByTestId('review-submit-proposal'), { note: 'เสนอผลทบทวน' })
    await d.confirm('ยืนยันเสนอผลทบทวน')

    // ───────── ผู้บังคับบัญชาเห็นชอบ ─────────
    await d.switchRole('supervisor', 'ผู้บังคับบัญชาเห็นชอบข้อเสนอส่งต่อกรมคุ้มครองสิทธิฯ', 'ผู้บังคับบัญชาชั้นต้นตรวจข้อเสนอผลทบทวน แล้วเห็นชอบหรือส่งคืนแก้ไข', REVIEW)
    await d.fill(p.getByPlaceholder('ความเห็น / เหตุผลที่ส่งคืน'), 'เห็นชอบ ครบเพดาน 180 วันแต่ยังมีภัย เห็นควรส่งต่อกรมคุ้มครองสิทธิฯ', { note: 'ความเห็นผู้บังคับบัญชา' })
    await d.click(p.getByTestId('review-endorse'), { note: 'เห็นชอบข้อเสนอ' })
    await d.confirm('ยืนยันเห็นชอบ')

    // ───────── เจ้าหน้าที่ดำเนินการ → เข้าเส้นทางส่งต่อ ─────────
    await d.switchRole('officer', 'เจ้าหน้าที่ดำเนินการส่งต่อกรมคุ้มครองสิทธิฯ', 'เมื่อได้รับความเห็นชอบ เจ้าหน้าที่ดำเนินการตามแนวทางที่เลือก ระบบพาเข้าเส้นทางส่งต่อกรมคุ้มครองสิทธิและเสรีภาพ', REVIEW)
    await d.click(p.getByTestId('review-apply-outcome'), { note: 'ดำเนินการตามแนวทางที่เห็นชอบ' })
    await d.confirm('ยืนยันดำเนินการ')
    d.section('เข้าเส้นทางส่งต่อกรมคุ้มครองสิทธิฯ', 'เมื่อดำเนินการแล้ว แฟ้มเปลี่ยนสถานะเป็นครบเพดานแต่ยังมีภัย เจ้าหน้าที่เปิดหน้า "ส่งต่อกรมคุ้มครองสิทธิและเสรีภาพ" เพื่อจัดทำเรื่องเสนอต่อ')
    await d.goto('/article14')
    await d.result(p.getByText(/คุ้มครองสะสม 180 วัน · คงเหลือ 0 วัน/).first(), `เรื่อง ${CASE_NO} ขึ้นในหน้าส่งต่อกรมคุ้มครองสิทธิฯ — คุ้มครองสะสม 180/180 วัน`)

    await article14ProposalSteps(d, CASE_NO)
  },
} satisfies GuideFlow
