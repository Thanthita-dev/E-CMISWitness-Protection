for (const [name, role, step] of [
  ['PostApproval 2', 'officer', 'accepted'], ['PostApproval 3', 'got_receiver', 'pending_receipt'],
  ['PostApproval 4', 'got_director', 'pending_assignment'], ['PostApproval 5', 'got_officer', 'assigned'],
] as const) {
  test(`ข้อมูลสาธิต ${name} เปิดคิวพร้อมเดินต่อและรีเฟรชได้`, async ({ page }) => {
    await seedMockState(page, name)
    await page.goto(`/queue/${role}`)
    const row = page.getByRole('row', { name: new RegExp(NO) })
    await expect(row).toContainText('ข้อมูลสำหรับสาธิต')
    await row.getByRole('link', { name: 'เปิดแฟ้ม' }).click()
    await expect(page.getByTestId('protection-handoff-card')).toContainText('ข้อมูลสำหรับสาธิต')
    await expect(page.getByTestId('protection-handoff-card')).toContainText('30 วัน')
    await page.reload()
    expect((await readHandoff(page))?.step).toBe(step)
    expect((await readCase(page, NO))?.mainCaseNo).toBe('กบค. 001/2569')
    if (role === 'got_director') await expect(page.getByTestId('got-assignee-select')).toBeVisible()
    if (role === 'got_receiver') await expect(page.getByTestId('got-receive-button')).toBeVisible()
    if (role === 'got_officer') await expect(page.getByTestId('got-accept-button')).toBeVisible()
  })
}

test('หน้ามอบหมาย กอท. ใช้ได้ที่ 1440 / 1024 / 768 / 390 และผัง 07G แสดงครบ', async ({ page }, testInfo) => {
  await seedMockState(page, 'PostApproval 4')
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(DOSSIER)
    const card = page.getByTestId('protection-handoff-card')
    await expect(card).toBeVisible()
    await expect(page.getByTestId('got-assignee-select')).toBeVisible()
    await expect(page.getByTestId('got-assign-button')).toBeVisible()
    const box = await card.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(width + 1)
    const controlsOverflow = await card.evaluate((el) => el.scrollWidth > el.clientWidth + 1)
    expect(controlsOverflow).toBe(false)
    await card.screenshot({ path: testInfo.outputPath(`got-assignment-${width}.png`) })
    await page.screenshot({ path: testInfo.outputPath(`dossier-${width}.png`), fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/flow-chart?tab=07G')
  await expect(page.getByRole('button', { name: /A6POST04/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /A6POST05/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('flow-07G.png'), fullPage: true })
})
