import { expect, test } from '@playwright/test'
import { seedMockState, readCase } from '../helpers/seed'

test('termination button exposes all four reasons before recording the source and preserves the selection', async ({ page }) => {
  await seedMockState(page, 'Case 1.13', 'officer', { terminationTrigger: undefined, kb15: undefined })
  await page.goto('/protection-duration?caseNo=0501%2F2569')
  await page.getByRole('link', { name: 'ยุติคุ้มครองพยาน', exact: true }).click()
  const choices = page.getByTestId('kb15-clause-choices')
  await expect(choices.getByRole('radio')).toHaveCount(4)
  await expect(page.getByTestId('termination-trigger-form')).toHaveCount(0)
  await expect(page.getByTestId('termination-statuses')).toHaveCount(0)
  for (const radio of await choices.getByRole('radio').all()) await expect(radio).toBeVisible()
  await choices.getByRole('radio', { name: /ข้อ 18 \(2\)/ }).click()
  if (await page.getByRole('button', { name: 'เปลี่ยนเหตุและตรวจใหม่', exact: true }).isVisible()) {
    await page.getByRole('button', { name: 'เปลี่ยนเหตุและตรวจใหม่', exact: true }).click()
  }
  await expect(choices.getByRole('radio', { name: /ข้อ 18 \(2\)/ })).toBeChecked()
  await page.reload()
  await expect(choices.getByRole('radio', { name: /ข้อ 18 \(2\)/ })).toBeChecked()
  await choices.getByRole('radio', { name: /ข้อ 18 \(4\)/ }).click()
  await page.getByRole('button', { name: 'เปลี่ยนเหตุและตรวจใหม่', exact: true }).click()
  await expect(page.getByTestId('kb15-reason-select')).toBeVisible()
  expect((await readCase(page, '0501/2569'))?.terminationTrigger).toBeFalsy()
  await expect(page.getByRole('textbox', { name: 'อ้างอิงเหตุยุติ', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'ลงนามหัวหน้าชุดปฏิบัติการ คบ.15' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'เปิดแบบ คบ.15', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'ไปส่งตรวจที่แฟ้มคำร้อง' })).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(choices.getByRole('radio')).toHaveCount(4)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => window.scrollTo(0, 0))
})

test('selecting witness request opens KB7 and saving returns to the same dossier', async ({ page }) => {
  await seedMockState(page, 'Case 1.13', 'officer', { terminationTrigger: undefined, kb15: undefined })
  await page.goto('/termination/0501%2F2569')
  await page.getByTestId('kb15-clause-choices').getByRole('radio', { name: /ข้อ 18 \(1\)/ }).click()
  await expect(page).toHaveURL(/termination\/0501%2F2569/)
  await page.getByRole('button', { name: 'ตกลง', exact: true }).click()
  await expect(page).toHaveURL(/form\/7\?caseNo=0501%2F2569/)
  await page.getByRole('button', { name: 'ดูครบทุกหน้า', exact: true }).click()
  await page.getByTestId('paper-sign-kb7-officer').click()
  await expect(page.getByRole('dialog', { name: 'ลงนามในฐานะเจ้าพนักงาน' })).toBeVisible()
  await page.getByRole('button', { name: 'ยกเลิก', exact: true }).click()
  await page.getByRole('radio', { name: 'กรอกผ่านแบบฟอร์ม', exact: true }).check()
  await page.getByPlaceholder('ระบุเหตุผลและผลการประเมินความปลอดภัยล่าสุด...').fill('พยานมีความประสงค์ขอยุติการคุ้มครอง')
  await page.getByRole('button', { name: /บันทึก คบ.7 และกลับแฟ้มคำร้อง/ }).click()
  await expect(page).toHaveURL(/dossier\/0501%2F2569/)
  await expect(page.getByRole('button', { name: 'ประวัติฉบับเอกสาร', exact: true })).toHaveCount(0)
  expect(await page.getByTestId('dossier-form-row').evaluateAll(rows => rows.slice(-3).map(row => row.getAttribute('data-form-number')))).toEqual(['15', '16', '17'])
  await expect(page.getByTestId('termination-forward-footer')).toBeVisible()
  await expect(page.getByTestId('dossier-forms').getByRole('button', { name: /ส่งตรวจ|ส่งให้อนุมัติ/ })).toHaveCount(0)
  for (const n of [7, 15, 16, 17]) await expect(page.locator(`[data-testid="dossier-form-row"][data-form-number="${n}"]`)).toBeVisible()
  await page.goto('/termination/0501%2F2569')
  const selected = page.getByTestId('kb15-clause-choices').getByRole('radio', { name: /ข้อ 18 \(1\)/ })
  await expect(selected).toBeChecked()
  await selected.click()
  await expect(page).toHaveURL(/termination\/0501%2F2569/)
  await page.getByRole('button', { name: 'ตกลง', exact: true }).click()
  await expect(page).toHaveURL(/form\/7\?caseNo=0501%2F2569/)
})

test('saving signed KB7 returns to dossier without asking for the reason again', async ({ page }) => {
  await seedMockState(page, 'Case 1.13', 'officer', { terminationTrigger: undefined, kb15: undefined })
  await page.goto('/form/7?caseNo=0501%2F2569&from=termination')
  await page.getByRole('button', { name: 'ดูครบทุกหน้า', exact: true }).click()
  await page.getByTestId('paper-sign-kb7-officer').click()
  await page.getByRole('button', { name: /ยืนยันลงนาม/ }).click()
  const before = await page.evaluate(() => localStorage.getItem('ecmis-form-draft-storage-v2'))
  await page.getByRole('button', { name: /บันทึก คบ.7 และกลับแฟ้มคำร้อง/ }).click()
  await expect(page).toHaveURL(/dossier\/0501%2F2569/)
  await expect(page.getByRole('button', { name: 'ประวัติฉบับเอกสาร', exact: true })).toHaveCount(0)
  expect(await page.getByTestId('dossier-form-row').evaluateAll(rows => rows.slice(-3).map(row => row.getAttribute('data-form-number')))).toEqual(['15', '16', '17'])
  await expect(page.getByTestId('termination-forward-footer')).toBeVisible()
  await expect(page.getByTestId('dossier-forms').getByRole('button', { name: /ส่งตรวจ|ส่งให้อนุมัติ/ })).toHaveCount(0)
  for (const n of [7, 15, 16, 17]) await expect(page.locator(`[data-testid="dossier-form-row"][data-form-number="${n}"]`)).toBeVisible()
  await expect(page.getByPlaceholder('เหตุผลที่พยานขอยุติการคุ้มครอง')).toHaveCount(0)
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('ecmis-form-draft-storage-v2')!).state)
  const original = JSON.parse(before!).state
  expect(after.signatures['kb7-officer']).toEqual(original.signatures['kb7-officer'])
  expect(after.revisions[7]).toEqual(original.revisions[7])
})
