    await page.goto(DOSSIER)
    const before = await readCase(page, NO)
    const notifications = await notificationCount(page)
    await choosePreliminaryOutcome(page, formNo)
    await assertFormCount(page)
    await expect(page.getByTestId('notice-decision-status')).toContainText('ร่าง')
