test('ยืนยันล้มเหลวยังคงข้อมูล ไม่มีผลสำเร็จ และลองใหม่ได้', async ({ page }) => {
  await seedMockState(page, 'PostApproval 1')
  await page.goto(DOSSIER)
  const before = await readCase(page, NO)
  const notifications = await notificationCount(page)
  await choosePreliminaryOutcome(page, 9)
  await fillDecisionWorkspace(page)
  await page.getByTestId('notice-decision-detail-เลขที่หนังสือ').fill('ปป RETRY')
  await page.evaluate(async () => {
    const path = '/scripts/post-approval-fixture.ts'
    const { useCaseStore } = await import(path)
    ;(window as any).__noticeWorkspaceConfirm = useCaseStore.getState().confirmPreliminaryDecision
    useCaseStore.setState({ confirmPreliminaryDecision: () => false })
  })
  await confirmInlineDecision(page, false)
  await expect(page.getByTestId('notice-decision-error')).toBeVisible()
  await expect(page.getByTestId('notice-decision-reason')).toHaveValue('ผลพิจารณาจากข้อเท็จจริงสมมติ')
  await expect(page.getByTestId('notice-decision-detail-เลขที่หนังสือ')).toHaveValue('ปป RETRY')
  await noFinalEffects(page, before, notifications)
  await page.evaluate(async () => {
    const path = '/scripts/post-approval-fixture.ts'
    const { useCaseStore } = await import(path)
    useCaseStore.setState({ confirmPreliminaryDecision: (window as any).__noticeWorkspaceConfirm })
    delete (window as any).__noticeWorkspaceConfirm
  })
  await confirmInlineDecision(page)
  await expect.poll(async () => (await readCase(page, NO))?.activity7State).toBe('approved')
})

test('พื้นที่แบบฟอร์มใช้งานด้วยคีย์บอร์ดที่390/1440และซูม200%ปุ่มเข้าถึงได้', async ({ page }) => {
  await seedMockState(page, 'PostApproval 1')
  await page.goto(DOSSIER)
  await choosePreliminaryOutcome(page, 9)
  await page.getByTestId('notice-decision-expand-preview').click()
  await expect(page.getByTestId('notice-decision-expand-preview')).toHaveAttribute('aria-expanded', 'true')
  await decisionWorkspace(page).getByRole('button', { name: 'หน้า 1', exact: true }).click()
  await expect(decisionWorkspace(page).getByRole('button', { name: 'หน้า 1', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByTestId('notice-decision-expand-preview').click()
  await expect(page.getByTestId('notice-decision-expand-preview')).toHaveAttribute('aria-expanded', 'false')
  for (const [width, zoom] of [[1440, '1'], [390, '1'], [1440, '2']] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.evaluate((value) => { document.documentElement.style.zoom = value }, zoom)
    await page.getByTestId('notice-decision-number').focus()
    await page.keyboard.press('Tab')
    expect(await decisionWorkspace(page).evaluate((el) => el.contains(document.activeElement))).toBe(true)
    expect(await page.evaluate(() => document.activeElement?.matches(':focus-visible'))).toBe(true)
    const workspaceBox = await decisionWorkspace(page).boundingBox()
    expect(workspaceBox!.x).toBeGreaterThanOrEqual(-1)
    expect(workspaceBox!.x + workspaceBox!.width).toBeLessThanOrEqual(width + 1)
    await page.getByTestId('notice-decision-confirm').scrollIntoViewIfNeeded()
    await expect(page.getByTestId('notice-decision-confirm')).toBeVisible()
    const button = await page.getByTestId('notice-decision-confirm').boundingBox()
    expect(button!.x).toBeGreaterThanOrEqual(-1)
    expect(button!.x + button!.width).toBeLessThanOrEqual(width + 1)
    expect(button!.y).toBeGreaterThanOrEqual(-1)
    expect(button!.y + button!.height).toBeLessThanOrEqual(1001)
    await page.screenshot({ path: `/private/tmp/a6-notice-workspace-${width}-zoom${zoom}.png`, fullPage: true })
  }
})
