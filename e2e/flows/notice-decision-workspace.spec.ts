test('ข้อมูลที่ยังไม่บันทึกเตือนก่อนย้อนกลับหรือรีเฟรช ยกเลิกแล้วคงข้อมูลเดิม', async ({ page }) => {
  await seedMockState(page, 'PostApproval 1')
  await page.goto(DOSSIER)
  const before = await readCase(page, NO)
  const notifications = await notificationCount(page)
  await choosePreliminaryOutcome(page, 9)
  await page.getByTestId('notice-decision-reason').fill('ข้อความที่ยังไม่บันทึก')
  let backWarning = ''
  page.once('dialog', async (dialog) => { backWarning = dialog.message(); await dialog.dismiss() })
  await page.getByTestId('notice-decision-back').click()
  expect(backWarning).toContain('ยังไม่บันทึก')
  await expect(decisionWorkspace(page)).toBeVisible()
  await expect(page.getByTestId('notice-decision-reason')).toHaveValue('ข้อความที่ยังไม่บันทึก')
  let reloadWarning = ''
  page.once('dialog', async (dialog) => { reloadWarning = dialog.type(); await dialog.dismiss() })
  // ยกเลิก beforeunload แล้วไม่มี navigation ให้รอจน load; อย่าให้กินเวลาเทสต์ทั้งหมด
  await page.reload({ timeout: 3000 }).catch(() => undefined)
  expect(reloadWarning).toBe('beforeunload')
  await expect(page.getByTestId('notice-decision-reason')).toHaveValue('ข้อความที่ยังไม่บันทึก')
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByTestId('notice-decision-back').click()
  await expect(decisionWorkspace(page)).toHaveCount(0)
  await choosePreliminaryOutcome(page, 10)
  await expect(decisionWorkspace(page)).toContainText('คบ.10')
  await noFinalEffects(page, before, notifications)
})

for (const destination of ['original_owner', 'got'] as const) {
  test(`ยืนยันจากพื้นที่แบบฟอร์มลงนามครั้งเดียวและส่งงาน ${destination} หลังยืนยันจริง`, async ({ page }) => {
    await seedMockState(page, 'PostApproval 1')
    await page.goto(DOSSIER)
    await choosePreliminaryOutcome(page, 9)
    await fillDecisionWorkspace(page, destination)
    await confirmInlineDecision(page)
    await expect.poll(async () => (await readCase(page, NO))?.activity7State).toBe('approved')
    const signed = await readCase(page, NO)
    expect((signed?.protectionHandoff as any)?.destination).toBe(destination)
    expect((signed?.resultNotices as any)?.[9]?.status).toBe('signed_incomplete')
    expect((signed?.resultNotices as any)?.[10]?.original).toBeUndefined()
    await expect(page.getByTestId('notice-decision-confirm')).toHaveCount(0)
    await expect(page.getByTestId('reject-case-button')).toHaveCount(0)
    const duplicate = await page.evaluate(async () => {
      const path = '/scripts/post-approval-fixture.ts'
      const { useCaseStore } = await import(path)
      return useCaseStore.getState().confirmPreliminaryDecision('WP-2569-000501', 9)
    })
    expect(duplicate).toBe(false)
    expect((await readCase(page, NO))?.documents).toEqual(signed?.documents)
    if (destination === 'got') {
      await role(page, 'got_receiver')
      await handoffAction(page, 'receive')
      await handoffAction(page, 'submit')
      await role(page, 'got_director')
      await page.getByTestId('got-assignee-select').selectOption('GOT-OFF-001')
      await handoffAction(page, 'assign', 'มอบหมายตามผลพิจารณาเดิม')
      await role(page, 'got_officer')
      await handoffAction(page, 'accept')
      expect((await readCase(page, NO))?.assignedOfficerUserId).toBe('OFF-001')
    }
    await page.reload()
    expect((await readCase(page, NO))?.kb9SignedAt).toBe(signed?.kb9SignedAt)
  })
}

